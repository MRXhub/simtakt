export function setLang(lang) {
  if (lang === "en" || lang === "zh") {
    currentLang = lang;
    if (typeof localStorage !== "undefined") {
      try { localStorage.setItem("eval_console_lang", lang); } catch (_) {}
    }
    if (typeof window !== "undefined" && window.location && window.history) {
      try {
        const url = new URL(window.location.href);
        if (url.searchParams.has("lang") && url.searchParams.get("lang") !== lang) {
          url.searchParams.set("lang", lang);
          window.history.replaceState(null, "", url.toString());
        }
      } catch (_) {}
    }
  }
}

export function t(key, vars) {
  const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.zh;
  let str = dict[key] || TRANSLATIONS.zh[key] || TRANSLATIONS.en[key] || key;
  if (vars && typeof vars === "object") {
    Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), vars[k]);
    });
  }
  return str;
}

export function fmtClockTime(date) {
  if (!date || !(date instanceof Date) || isNaN(date.getTime())) return "—";
  const pad = n => (n < 10 ? "0" + n : n);
  return `${pad(date.getHours())}:${pad(date.getMinutes())}:${pad(date.getSeconds())}`;
}

export function fmtDate(date) {
  if (!date || !(date instanceof Date) || isNaN(date.getTime())) return "—";
  const pad = n => (n < 10 ? "0" + n : n);
  return `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())} ${fmtClockTime(date)}`;
}

export function fmtDuration(seconds) {
  if (seconds === null || seconds === undefined || isNaN(seconds) || seconds < 0) return "—";
  const s = Math.round(seconds);
  if (s < 60) return `${s}${t("secUnit")}`;
  const m = Math.floor(s / 60);
  const remS = s % 60;
  if (m < 60) return `${m}${t("minUnit")} ${remS}${t("secUnit")}`;
  const h = Math.floor(m / 60);
  const remM = m % 60;
  if (h < 24) return `${h}${t("hourUnit")} ${remM}${t("minUnit")}`;
  const d = Math.floor(h / 24);
  const remH = h % 24;
  return `${d}${t("dayUnit")} ${remH}${t("hourUnit")}`;
}

export function fmtRelativeTime(isoString) {
  if (!isoString) return "—";
  const d = new Date(isoString);
  if (isNaN(d.getTime())) return "—";
  const diffSec = Math.max(0, Math.floor((Date.now() - d.getTime()) / 1000));
  if (diffSec < 10) return t("justNow");
  return `${fmtDuration(diffSec)} ${t("agoSuffix")}`;
}

export function fmtNumericValue(val) {
  if (val === null || val === undefined || val === "") return "—";
  if (typeof val === "number" || (!isNaN(Number(val)) && typeof val === "string" && val.trim() !== "")) {
    const num = Number(val);
    if (!Number.isFinite(num)) return String(val);
    const abs = Math.abs(num);
    if (num !== 0 && (abs >= 1e4 || abs <= 1e-3)) {
      const exp = num.toExponential();
      return exp.replace(/\.0+e/, "e").replace(/(\.\d*?[1-9])0+e/, "$1e").replace(/e\+?(-?\d+)/, "e$1");
    }
    return String(num);
  }
  return String(val);
}

export function fmtBytes(bytes) {
  if (bytes === null || bytes === undefined || isNaN(bytes) || bytes <= 0) return "—";
  const units = ["B", "KB", "MB", "GB", "TB"];
  let val = bytes;
  let u = 0;
  while (val >= 1024 && u < units.length - 1) {
    val /= 1024;
    u++;
  }
  return `${val.toFixed(1)} ${units[u]}`;
}
